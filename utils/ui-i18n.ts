export function t(key: string, vars?: Record<string, string | number>): string {
    let s = STRINGS[lang][key] ?? STRINGS.ja[key] ?? key;
    if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
}

/**
 * 活動限定的兩個支援遠征。真封包 `api_mst_mission` 實測（samples/start2-master.json）：
 * id 301＝`S1` 前衛支援任務、302＝`S2` 艦隊決戦支援任務，兩者的 `api_maparea_id` 都是
 * 活動海域（樣本為 62），故只在活動期間出現在遠征清單裡。
 *
 * 加註的理由：遊戲名稱講「前衛／決戦」，攻略圈與使用者講「道中／王點」，兩套詞彙對不
 * 起來，光看名稱容易派錯支援。**以 mission master id 為鍵而非 `api_disp_no`**——顯示
 * 編號是給人看的字串，master id 才是封包主鍵；一般海域的 33／34 號支援遠征不在此列。
 */
const EVENT_SUPPORT_MISSIONS: Record<number, string> = {
    301: 'exped.supportRoute',
    302: 'exped.supportBoss',
};

/** 上表的查詢入口。不是活動支援遠征就回 null（不加註，不猜）。 */
export function expedSupportNote(missionId: number): string | null {
    const key = EVENT_SUPPORT_MISSIONS[missionId];
    return key ? t(key) : null;
}

/** 遠征顯示名：活動支援遠征補上白話註記，其餘原樣回傳封包名稱。 */
export function expedDisplayName(missionId: number, name: string): string {
    const note = expedSupportNote(missionId);
    return note ? `${name}（${note}）` : name;
}
